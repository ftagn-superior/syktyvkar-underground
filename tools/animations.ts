import { createHash, randomUUID } from 'node:crypto';
import { readFile, writeFile, readdir, mkdir, rename, rm } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { format, resolveConfig } from 'prettier';
import type { AnimationDefinition } from '../packages/contracts/src/animations.js';
import { validateAnimationDefinitions } from '../packages/contracts/src/animation-validation.js';
import { validateAnimationClips } from './animation-validation.js';
import type { AnimationClip } from '../apps/client/src/rendering/avatars/clips/types.js';

const manifest = 'content/animations/catalog.json';
const clipsDirectory = 'apps/client/src/rendering/avatars/clips';
const contractsIndex = 'packages/contracts/src/animation-catalog.generated.ts';
const clientIndex = 'apps/client/src/rendering/avatars/animation-clips.generated.ts';
const header =
  '// Generated by pnpm animations:sync. Edit content/animations/catalog.json and clips/*.ts.\n';
const json = (value: unknown) => JSON.stringify(value, null, 2) + '\n';
const reject = (errors: readonly string[]) => {
  if (errors.length) throw new Error(errors.join('\n'));
};

async function catalog(root: string) {
  const source: unknown = JSON.parse(await readFile(resolve(root, manifest), 'utf8'));
  reject(validateAnimationDefinitions(source));
  const definitions = (source as AnimationDefinition[]).map(
    ({ id, label, category, cooldownMs, mode, rig, seated }) => ({
      id,
      label,
      category,
      cooldownMs,
      mode,
      rig,
      seated,
    }),
  );
  const files = (await readdir(resolve(root, clipsDirectory)))
    .filter((name) => name.endsWith('.ts') && name !== 'types.ts')
    .sort();
  const expected = definitions.map((entry) => `${entry.id}.ts`).sort();
  reject([
    ...expected
      .filter((file) => !files.includes(file))
      .map((file) => `${clipsDirectory}/${file}: missing implementation`),
    ...files
      .filter((file) => !expected.includes(file))
      .map((file) => `${clipsDirectory}/${file}: orphan implementation without metadata`),
  ]);
  const clips: Record<string, AnimationClip> = {};
  for (const { id } of definitions) {
    const file = resolve(root, clipsDirectory, `${id}.ts`);
    try {
      clips[id] = (await import(`${pathToFileURL(file).href}?authoring=${randomUUID()}`)).clip;
    } catch (error) {
      throw new Error(`${clipsDirectory}/${id}.ts: cannot load clip: ${String(error)}`);
    }
  }
  reject(validateAnimationClips(definitions, clips));
  // Canonical metadata, source paths and implementation bytes define exact compatibility.
  const hash = createHash('sha256').update('su-animation-catalog-v1\n').update(json(definitions));
  for (const file of ['types.ts', ...files])
    hash.update(file + '\0').update(await readFile(resolve(root, clipsDirectory, file)));
  const version = hash.digest('hex');
  const contracts =
    header +
    "import type { AnimationDefinition } from './animations.js';\n" +
    `export const ANIMATION_CATALOG_VERSION = '${version}';\n` +
    `export const ANIMATIONS = ${JSON.stringify(definitions, null, 2)} as const satisfies readonly AnimationDefinition[];\n`;
  const client =
    header +
    "import type { AnimationId } from '@su/contracts';\nimport type { AnimationClip } from './clips/types';\n" +
    definitions.map(({ id }, i) => `import { clip as clip${i} } from './clips/${id}';`).join('\n') +
    '\nexport const ANIMATION_CLIPS: Record<AnimationId, AnimationClip> = {\n' +
    definitions.map(({ id }, i) => `  '${id}': clip${i},`).join('\n') +
    '\n};\n';
  const options = {
    ...((await resolveConfig(resolve(root, '.prettierrc.json'))) ?? {
      singleQuote: true,
      printWidth: 100,
      trailingComma: 'all' as const,
    }),
    parser: 'typescript',
  };
  return {
    definitions,
    version,
    outputs: new Map([
      [contractsIndex, await format(contracts, options)],
      [clientIndex, await format(client, options)],
    ]),
  };
}

/** Restore originals if any write or subsequent validation fails. No partial addition. */
async function transaction(
  root: string,
  files: Map<string, string>,
  verify?: () => Promise<unknown>,
) {
  const originals = new Map<string, string | undefined>();
  const pending = new Set<string>();
  for (const file of files.keys()) {
    try {
      originals.set(file, await readFile(resolve(root, file), 'utf8'));
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
      originals.set(file, undefined);
    }
  }
  try {
    for (const [file, text] of files) {
      const target = resolve(root, file),
        temp = `${target}.animation-${process.pid}.tmp`;
      await mkdir(dirname(target), { recursive: true });
      pending.add(temp);
      await writeFile(temp, text, { flag: 'wx' });
      await rename(temp, target);
      pending.delete(temp);
    }
    await verify?.();
  } catch (error) {
    for (const [file, text] of originals) {
      if (text === undefined) await rm(resolve(root, file), { force: true });
      else await writeFile(resolve(root, file), text);
    }
    throw error;
  } finally {
    for (const file of pending) await rm(file, { force: true });
  }
}

export async function checkAnimations(root = process.cwd()) {
  const result = await catalog(root);
  for (const [file, expected] of result.outputs) {
    let actual: string | undefined;
    try {
      actual = await readFile(resolve(root, file), 'utf8');
    } catch {
      /* Report a missing index as stale. */
    }
    if (actual !== expected)
      throw new Error(
        `${file}: missing or stale registration/fingerprint; run pnpm animations:sync`,
      );
  }
  return result;
}

export async function syncAnimations(root = process.cwd()) {
  const result = await catalog(root);
  await transaction(root, result.outputs);
  return result;
}

function template(mode: AnimationDefinition['mode'], period: number): string {
  const body =
    mode === 'upperBody'
      ? 'pose.rightArm = -0.18;\n    pose.rightArmYaw = 0.12 * Math.sin(phase);\n    pose.rightArmRoll = 2.5 + 0.2 * Math.sin(phase);'
      : 'pose.leftArm = pose.rightArm = -0.5;\n    pose.leftArmYaw = pose.rightArmYaw = 0;\n    pose.leftArmRoll = -0.8;\n    pose.rightArmRoll = 0.8;\n    pose.leftLeg = 0.2 * Math.sin(phase);\n    pose.rightLeg = -pose.leftLeg;\n    pose.lean = 0;\n    pose.roll = 0.08 * Math.sin(phase) * (reduced ? 0.2 : 1);\n    pose.lift = 0;';
  const mask = mode === 'upperBody' ? 'rightArm' : 'fullBody';
  return `import { type AnimationClip, ${mask}, cycle } from './types';\n\n// Replace the starter pose; keep every masked channel assigned on each call.\nconst periodMs = ${period};\nexport const clip: AnimationClip = {\n  rig: 'humanoid-v1',\n  periodMs,\n  mask: ${mask},\n  sample(pose, ms${mode === 'fullBody' ? ', reduced' : ''}) {\n    const phase = cycle(ms, periodMs);\n    ${body}\n  },\n};\n`;
}

export async function animationCommand(root: string, args: string[]) {
  const [command, ...raw] = args;
  if (command !== 'add' && command !== 'check' && command !== 'sync')
    throw new Error(
      'Usage: animations:add -- --id salute --label "Отдать честь" --category Общение --mode upperBody [--cooldown-ms 1000] [--period-ms 1800]; animations:check; animations:sync',
    );
  const { values } = parseArgs({
    args: raw[0] === '--' ? raw.slice(1) : raw,
    options: {
      id: { type: 'string' },
      label: { type: 'string' },
      category: { type: 'string' },
      mode: { type: 'string' },
      'cooldown-ms': { type: 'string' },
      'period-ms': { type: 'string' },
    },
    strict: true,
  });
  if (command !== 'add' && Object.keys(values).length)
    throw new Error(`${command}: no authoring options expected`);
  if (command === 'check') return checkAnimations(root);
  const lock = resolve(root, 'content/animations/.authoring.lock');
  try {
    await writeFile(lock, String(process.pid), { flag: 'wx' });
  } catch (error) {
    throw new Error(
      `Cannot acquire ${lock}: another authoring command may be running (${String(error)})`,
    );
  }
  try {
    if (command === 'sync') return await syncAnimations(root);
    const current = await checkAnimations(root);
    const entry = {
      id: values.id,
      label: values.label,
      category: values.category,
      mode: values.mode,
      cooldownMs: Number(values['cooldown-ms'] ?? 1000),
      rig: 'humanoid-v1',
      seated: 'preserve-seat',
    };
    reject(validateAnimationDefinitions([...current.definitions, entry]));
    const period = Number(values['period-ms'] ?? 1800);
    if (!Number.isFinite(period) || period < 100 || period > 60_000)
      throw new Error(`animation ${entry.id}: period-ms must be in 100..60000 milliseconds`);
    const file = `${clipsDirectory}/${entry.id}.ts`;
    // checkAnimations already rejects orphans; never replace an implementation.
    try {
      await readFile(resolve(root, file));
      throw new Error(`${file}: already exists`);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    }
    const backups = new Map(current.outputs);
    backups.set(manifest, await readFile(resolve(root, manifest), 'utf8'));
    await transaction(
      root,
      new Map([
        [manifest, json([...current.definitions, entry])],
        [file, template(entry.mode as AnimationDefinition['mode'], period)],
      ]),
      async () => {
        try {
          await syncAnimations(root);
          await checkAnimations(root);
        } catch (error) {
          await transaction(root, backups);
          throw error;
        }
      },
    );
    return await checkAnimations(root);
  } finally {
    await rm(lock, { force: true });
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try {
    const result = await animationCommand(process.cwd(), process.argv.slice(2));
    console.log(
      `Animations OK: ${result.definitions.length} clips; compatible humanoid-v1 skins, masks and reduced motion checked.\nCatalog ${result.version}\nNext: pnpm check; pnpm test:animations:browser (export SU_TEST_DATABASE_URL). See docs/add-animation.md.`,
    );
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
